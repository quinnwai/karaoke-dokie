// Puts every popularity source on one scale and writes it to src/lib/songs/popularityScale.ts
// (QWW-32; how, in src/lib/popularity/calibrate.ts). Reads the measured catalogue's USDB views and
// karaoke popularity and Deezer rank (song_deezer), plus Spotify popularity from signed-in libraries when Spotify sends it.
// Usage: npm run popularity:calibrate [-- --dry-run] [--no-spotify]
// Needs DATABASE_URL (run usdb:index first), and for Spotify SPOTIFY_CLIENT_ID/SECRET/REDIRECT_URI.
// Rerun after usdb:index or popularity:import changes the numbers a lot.

import { writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import { calibrate, type CalibrationSong } from '../src/lib/popularity/calibrate';
import { readConfig } from '../src/lib/server/config';
import { getStore, neonQuery } from '../src/lib/server/getStore';
import { createSpotifyClient, ensureFreshTokens, getUserTracks } from '../src/lib/server/spotify';
import { songKey } from '../src/lib/songs/resolve';
import { MEASURED_RANK, SOURCE_RANK } from '../src/lib/songs/sourceRank';

const OUT = 'src/lib/songs/popularityScale.ts';

const num = (v: unknown): number | undefined => (v === null || v === undefined || v === '' ? undefined : Number(v));

async function spotifyPopularity(): Promise<Map<string, number>> {
  const store = getStore();
  const spotify = createSpotifyClient(readConfig().spotify);
  const out = new Map<string, number>();
  for (const id of await store.listUserIds()) {
    const user = await store.getUser(id);
    if (!user) continue;
    const tracks = await getUserTracks(spotify, (await ensureFreshTokens(user, spotify, store)).spotify.accessToken);
    const withPopularity = tracks.filter((t) => typeof t.popularity === 'number');
    console.log(`${user.displayName}: ${tracks.length} songs, ${withPopularity.length} with Spotify popularity`);
    for (const t of withPopularity) out.set(songKey(t.artist, t.title), t.popularity!);
  }
  return out;
}

async function main() {
  const { values } = parseArgs({ options: { 'dry-run': { type: 'boolean' }, 'no-spotify': { type: 'boolean' } } });
  const url = process.env.DATABASE_URL?.trim();
  if (!url) throw new Error('Set DATABASE_URL');
  const query = neonQuery(url);
  const sources = Object.entries(SOURCE_RANK).filter(([, rank]) => rank >= MEASURED_RANK).map(([source]) => source);
  // The same numbers listCatalogue ranks with: the range's own USDB views, else its most-viewed USDB row's.
  const rows = await query(
    `SELECT s.song_key,
       COALESCE((s.range_json::json ->> 'usdbViews')::numeric, b.views) AS views,
       p.karaoke_views, p.chart_rank, d.rank AS deezer_rank
     FROM song_ranges s
     LEFT JOIN (SELECT DISTINCT ON (song_key) song_key, views FROM usdb_songs ORDER BY song_key, COALESCE(views, 0) DESC, id) b
       ON b.song_key = s.song_key
     LEFT JOIN song_popularity p ON p.song_key = s.song_key
     LEFT JOIN song_deezer d ON d.song_key = s.song_key
     WHERE s.skipped = false AND (s.range_json::json ->> 'source') IN (${sources.map((_, i) => `$${i + 1}`).join(', ')})`,
    sources,
  );
  const spotify = values['no-spotify'] ? new Map<string, number>() : await spotifyPopularity();
  const songs: CalibrationSong[] = rows.map((r) => {
    const s: CalibrationSong = {};
    const set = (k: keyof CalibrationSong, v: number | undefined) => {
      if (v !== undefined) s[k] = v;
    };
    set('usdbViews', num(r.views));
    set('karaokeViews', num(r.karaoke_views));
    set('chartRank', num(r.chart_rank));
    set('deezerRank', num(r.deezer_rank));
    set('spotify', spotify.get(String(r.song_key)));
    return s;
  });
  const { scale, counts } = calibrate(songs);
  console.log(JSON.stringify({ songs: songs.length, counts, chartFloor: scale.chartFloor }));
  if (values['dry-run']) {
    console.log(JSON.stringify(scale));
    return;
  }
  const body = `// Generated by \`npm run popularity:calibrate\` (scripts/popularity-calibrate.ts); do not edit by hand.
// One popularity scale for every source (src/lib/popularity/calibrate.ts), from ${songs.length} measured
// songs: ${counts.anchor} with USDB views, ${counts.karaokeViews} of them with karaoke views, ${counts.deezer} with a
// Deezer rank and ${counts.spotify} with Spotify popularity; ${counts.top20} top-20 and ${counts.top100} other Year-End songs.

import type { PopularityScale } from '../popularity/calibrate';

export const POPULARITY_SCALE: PopularityScale = ${JSON.stringify(scale)};
`;
  await writeFile(OUT, body);
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
